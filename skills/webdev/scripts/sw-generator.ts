#!/usr/bin/env bun
/**
 * sw-generator.ts: Progressive Web App & Offline-First Generator & Auditor.
 *
 * Implements PWA-001 through PWA-004:
 *   - PWA-001: Two-Tier Caching Architecture (CacheFirst for static, NetworkFirst for dynamic)
 *   - PWA-002: Offline Mutation Queue & Optimistic UI integration
 *   - PWA-003: Background Sync & Auto-Reconnection Lifecycle
 *   - PWA-004: Manifest & Installation Compliance
 *
 * Usage:
 *   bun sw-generator.ts --generate-sw [--output <file>] [--json]
 *   bun sw-generator.ts --generate-manifest [--name <name>] [--output <file>] [--json]
 *   bun sw-generator.ts --audit-pwa <dir> [--json]
 */

import fs from "node:fs";
import path from "node:path";

export interface PwaAuditResult {
  targetDir: string;
  score: number;
  passed: boolean;
  hasServiceWorker: boolean;
  hasManifest: boolean;
  hasOfflineHtml: boolean;
  hasIcons: boolean;
  findings: string[];
  recommendations: string[];
}

export function generateServiceWorker(version = "1.0.0", offlinePage = "/offline.html"): string {
  return `/**
 * Service Worker: Generated by Muse WebDev Engine (PWA-001 - PWA-004)
 * Version: v${version}
 */

const CACHE_VERSION = 'v${version}';
const STATIC_CACHE = \`static-\${CACHE_VERSION}\`;
const RUNTIME_CACHE = \`runtime-\${CACHE_VERSION}\`;
const OFFLINE_URL = '${offlinePage}';

const PRECACHE_ASSETS = [
  '/',
  '${offlinePage}',
  '/manifest.webmanifest',
  '/favicon.ico'
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(STATIC_CACHE).then((cache) => cache.addAll(PRECACHE_ASSETS))
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(
        keys
          .filter((k) => k !== STATIC_CACHE && k !== RUNTIME_CACHE)
          .map((k) => caches.delete(k))
      )
    )
  );
  self.clients.claim();
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  const url = new URL(request.url);

  // Skip non-GET requests (mutations route to client-side IndexedDB queue)
  if (request.method !== 'GET') return;

  // 1. Static Assets: CacheFirst
  if (url.origin === self.location.origin && /\\.(css|js|woff2|png|svg|webp|ico|jpg|jpeg)$/.test(url.pathname)) {
    event.respondWith(
      caches.match(request).then((cached) => {
        if (cached) return cached;
        return fetch(request).then((response) => {
          if (!response || response.status !== 200 || response.type !== 'basic') {
            return response;
          }
          const clone = response.clone();
          caches.open(STATIC_CACHE).then((cache) => cache.put(request, clone));
          return response;
        });
      })
    );
    return;
  }

  // 2. Navigation / HTML: NetworkFirst with 3s Timeout
  if (request.mode === 'navigate') {
    event.respondWith(
      Promise.race([
        fetch(request).then((response) => {
          const clone = response.clone();
          caches.open(RUNTIME_CACHE).then((cache) => cache.put(request, clone));
          return response;
        }),
        new Promise((_, reject) => setTimeout(() => reject(new Error('Network timeout')), 3000))
      ]).catch(() => caches.match(request).then((cached) => cached || caches.match(OFFLINE_URL)))
    );
  }
});

// PWA-003: Background Sync event
self.addEventListener('sync', (event) => {
  if (event.tag === 'sync-mutations') {
    event.waitUntil(
      self.clients.matchAll().then((clients) => {
        clients.forEach((client) => {
          client.postMessage({ type: 'SYNC_TRIGGERED', timestamp: Date.now() });
        });
      })
    );
  }
});
`;
}

export function generateManifest(
  name = "Agency Web Application",
  shortName = "App",
  themeColor = "#0f172a",
  bgColor = "#ffffff",
): string {
  const manifest = {
    name,
    short_name: shortName,
    start_url: "/",
    display: "standalone",
    background_color: bgColor,
    theme_color: themeColor,
    orientation: "any",
    description: "Progressive Web Application built with modern offline-first standards.",
    icons: [
      {
        src: "/icons/icon-192x192.png",
        sizes: "192x192",
        type: "image/png",
        purpose: "any",
      },
      {
        src: "/icons/icon-512x512.png",
        sizes: "512x512",
        type: "image/png",
        purpose: "any",
      },
      {
        src: "/icons/icon-maskable-512x512.png",
        sizes: "512x512",
        type: "image/png",
        purpose: "maskable",
      },
    ],
  };

  return JSON.stringify(manifest, null, 2);
}

export function auditPwaReadiness(targetDir: string): PwaAuditResult {
  const findings: string[] = [];
  const recommendations: string[] = [];
  let score = 0;

  if (!fs.existsSync(targetDir)) {
    return {
      targetDir,
      score: 0,
      passed: false,
      hasServiceWorker: false,
      hasManifest: false,
      hasOfflineHtml: false,
      hasIcons: false,
      findings: ["Target directory does not exist."],
      recommendations: ["Specify a valid directory path."],
    };
  }

  // Check 1: Service Worker (30 pts)
  const swPaths = [
    path.join(targetDir, "sw.js"),
    path.join(targetDir, "service-worker.js"),
    path.join(targetDir, "public", "sw.js"),
    path.join(targetDir, "src", "sw.js"),
  ];
  const hasServiceWorker = swPaths.some((p) => fs.existsSync(p));
  if (hasServiceWorker) {
    score += 30;
  } else {
    findings.push("Missing Service Worker script (sw.js / public/sw.js).");
    recommendations.push("Generate a service worker script via `bun sw-generator.ts --generate-sw`.");
  }

  // Check 2: Web App Manifest (25 pts)
  const manifestPaths = [
    path.join(targetDir, "manifest.webmanifest"),
    path.join(targetDir, "manifest.json"),
    path.join(targetDir, "public", "manifest.webmanifest"),
    path.join(targetDir, "public", "manifest.json"),
  ];
  const hasManifest = manifestPaths.some((p) => fs.existsSync(p));
  if (hasManifest) {
    score += 25;
  } else {
    findings.push("Missing Web App Manifest (manifest.webmanifest).");
    recommendations.push("Generate a compliant manifest via `bun sw-generator.ts --generate-manifest`.");
  }

  // Check 3: Offline Fallback Shell (25 pts)
  const offlinePaths = [path.join(targetDir, "offline.html"), path.join(targetDir, "public", "offline.html")];
  const hasOfflineHtml = offlinePaths.some((p) => fs.existsSync(p));
  if (hasOfflineHtml) {
    score += 25;
  } else {
    findings.push("Missing static offline fallback shell (offline.html).");
    recommendations.push("Provide an informative `/offline.html` page cached at install time.");
  }

  // Check 4: PWA Icons (20 pts)
  const iconPaths = [
    path.join(targetDir, "public", "icons"),
    path.join(targetDir, "icons"),
    path.join(targetDir, "public", "icon-192x192.png"),
  ];
  const hasIcons = iconPaths.some((p) => fs.existsSync(p));
  if (hasIcons) {
    score += 20;
  } else {
    findings.push("Missing 192x192 and 512x512 PWA icons.");
    recommendations.push("Add standard and maskable icons under `/public/icons/`.");
  }

  return {
    targetDir,
    score,
    passed: score >= 75 && hasServiceWorker && hasManifest,
    hasServiceWorker,
    hasManifest,
    hasOfflineHtml,
    hasIcons,
    findings,
    recommendations,
  };
}

// CLI Execution Harness
if (import.meta.main) {
  const args = process.argv.slice(2);
  const isJson = args.includes("--json");

  const swIdx = args.indexOf("--generate-sw");
  if (swIdx !== -1) {
    const outIdx = args.indexOf("--output");
    const outFile = outIdx !== -1 ? args[outIdx + 1] : undefined;
    const content = generateServiceWorker();

    if (outFile) {
      const dir = path.dirname(outFile);
      if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(outFile, content, "utf8");
    }

    if (isJson) {
      console.log(JSON.stringify({ generated: "service-worker", outFile, length: content.length }, null, 2));
    } else {
      if (outFile) {
        console.log(`\n✅ Generated Service Worker to ${outFile}`);
      } else {
        console.log(content);
      }
    }
    process.exit(0);
  }

  const manifestIdx = args.indexOf("--generate-manifest");
  if (manifestIdx !== -1) {
    const nameIdx = args.indexOf("--name");
    const appName = nameIdx !== -1 ? args[nameIdx + 1] : "Agency Web Application";
    const outIdx = args.indexOf("--output");
    const outFile = outIdx !== -1 ? args[outIdx + 1] : undefined;
    const content = generateManifest(appName);

    if (outFile) {
      const dir = path.dirname(outFile);
      if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(outFile, content, "utf8");
    }

    if (isJson) {
      console.log(JSON.stringify({ generated: "manifest", appName, outFile }, null, 2));
    } else {
      if (outFile) {
        console.log(`\n✅ Generated Web App Manifest to ${outFile}`);
      } else {
        console.log(content);
      }
    }
    process.exit(0);
  }

  const auditIdx = args.indexOf("--audit-pwa");
  if (auditIdx !== -1 && args[auditIdx + 1]) {
    const target = args[auditIdx + 1];
    const report = auditPwaReadiness(target);

    if (isJson) {
      console.log(JSON.stringify(report, null, 2));
    } else {
      console.log(`\n📱 PWA Readiness Audit: ${report.targetDir}`);
      console.log(`Score:   ${report.score}/100`);
      console.log(`Verdict: ${report.passed ? "PASS (PWA READY)" : "FAIL (INCOMPLETE)"}\n`);

      console.log("Checklist:");
      console.log(`  [${report.hasServiceWorker ? "✓" : "✗"}] Service Worker Script`);
      console.log(`  [${report.hasManifest ? "✓" : "✗"}] Web App Manifest`);
      console.log(`  [${report.hasOfflineHtml ? "✓" : "✗"}] Offline Fallback Shell`);
      console.log(`  [${report.hasIcons ? "✓" : "✗"}] PWA Icons\n`);

      if (report.findings.length > 0) {
        console.log("Defects:");
        for (const f of report.findings) console.log(`  • ${f}`);
      }
      if (report.recommendations.length > 0) {
        console.log("\nRecommendations:");
        for (const r of report.recommendations) console.log(`  • ${r}`);
      }
    }
    process.exit(report.passed ? 0 : 1);
  }

  console.log(`sw-generator.ts — Progressive Web App & Offline Architecture Tool

Usage:
  bun sw-generator.ts --generate-sw [--output <file>] [--json]
  bun sw-generator.ts --generate-manifest [--name <name>] [--output <file>] [--json]
  bun sw-generator.ts --audit-pwa <dir> [--json]
`);
  process.exit(0);
}
